#!/usr/bin/env python3
"""Writes ndk_exports.rs: every Android NDK system library and the functions it exports, from the
NDK's stub libraries for the highest API level it ships, for x86_64 and arm64 together. The NDK
generates those stubs from AOSP's `.map.txt` files, so these are Android's official exports. Run in
the dev image, which has the NDK:

    python3 crates/bridge/src/ndk_exports.py > crates/bridge/src/ndk_exports.rs

The loader binds a function import nothing else resolves to a stub that stops the program naming it,
but only when the name is on the list of a library the importing library needs: a name on no list
is not Android API, and keeps failing the load.
"""
import os
import re
import subprocess

NDK = os.environ["ANDROID_NDK_ROOT"]
PREBUILT = f"{NDK}/toolchains/llvm/prebuilt/linux-x86_64"
TRIPLES = ["x86_64-linux-android", "aarch64-linux-android"]
# A linker script, not a library: apps ship their own C++ runtime.
SKIPPED = {"libc++.so"}
FUNCTION_KINDS = {"T", "W", "i"}


def revision():
    """The NDK release, which the Dockerfile pins; the image keeps only its toolchain."""
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../Dockerfile")) as file:
        for line in file:
            if line.startswith("ARG NDK_VERSION="):
                return line.split("=", 1)[1].strip()
    return "unknown"


def highest_api(triple):
    base = f"{PREBUILT}/sysroot/usr/lib/{triple}"
    return max(int(entry) for entry in os.listdir(base) if entry.isdigit())


def functions(path):
    output = subprocess.run(
        [f"{PREBUILT}/bin/llvm-nm", "-D", "--defined-only", path],
        check=True, capture_output=True, text=True).stdout
    names = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[1] in FUNCTION_KINDS:
            # Versioned names, `name@@LIBC` and `name@LIBC_N`, are one export.
            names.add(fields[2].split("@")[0])
    names.discard("")
    return names


def main():
    apis = {triple: highest_api(triple) for triple in TRIPLES}
    libraries = {}
    for triple, api in apis.items():
        directory = f"{PREBUILT}/sysroot/usr/lib/{triple}/{api}"
        for entry in sorted(os.listdir(directory)):
            if not re.fullmatch(r"lib.+\.so", entry) or entry in SKIPPED:
                continue
            libraries.setdefault(entry, set()).update(functions(f"{directory}/{entry}"))
    api = ", ".join(f"{triple} {api}" for triple, api in apis.items())
    print(f"// Generated by ndk_exports.py from the stub libraries of NDK {revision()} (API {api}).")
    print("// Do not edit.")
    print()
    total = 0
    rows = []
    for library in sorted(libraries):
        names = sorted(libraries[library])
        rows.append((library, total, names))
        total += len(names)
    print("/// Every function of all the libraries below, which is how many stubs there are.")
    print(f"pub(crate) const FUNCTIONS: usize = {total};")
    print()
    print("/// Each NDK system library, the index of its first function among all of them, and its")
    print("/// functions, sorted.")
    print("pub(crate) const LIBRARIES: &[(&str, usize, &[&str])] = &[")
    for library, first, names in rows:
        print(f'    ("{library}", {first}, &[')
        for name in names:
            print(f'        "{name}",')
        print("    ]),")
    print("];")


main()
