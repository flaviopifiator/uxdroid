#!/usr/bin/env python3
"""Writes jni_table.rs: every JNIEnv function in the NDK's jni.h, in table order, with its signature
in the bridge's vocabulary. Usage: jni_table.py <ndk sysroot jni.h> > jni_table.rs"""
import re
import sys

TYPES = {
    "void": "void", "jboolean": "u8", "jbyte": "i8", "jchar": "u16", "jshort": "i16",
    "jint": "i32", "jsize": "i32", "jlong": "i64", "jfloat": "f32", "jdouble": "f64",
    "va_list": "va_list", "jobjectRefType": "i32",
}

def kind(text):
    text = text.replace("const", "").strip()
    if "*" in text:
        return "ptr"
    return TYPES.get(text, "ptr")  # every j-reference type and ID is a pointer

source = open(sys.argv[1]).read()
body = re.search(r"struct JNINativeInterface \{(.*?)\n\};", source, re.S).group(1)
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
entries = []
for member in body.split(";"):
    member = " ".join(member.split())
    if not member:
        continue
    if member.startswith("void* reserved"):
        entries.append((member.split()[-1], None))
        continue
    match = re.fullmatch(r"(.+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)", member)
    if not match:
        sys.exit(f"cannot parse {member!r}")
    returns, name, arguments = match.groups()
    parameters = [a.strip() for a in arguments.split(",")]
    kinds = ["..." if p == "..." else kind(re.sub(r"\b\w+$", "", p) if re.search(r"\w\s+\w+$", p) and p.split()[-1] not in TYPES else p) for p in parameters]
    entries.append((name, f"{kind(returns)}({','.join(kinds)})"))

print("// Generated by jni_table.py from the NDK's jni.h. Do not edit.")
print("")
print("/// Every `JNINativeInterface` slot in order: its name and, but for the reserved ones, signature.")
print(f"pub(crate) const FUNCTIONS: [(&str, Option<&str>); {len(entries)}] = [")
for name, signature in entries:
    value = "None" if signature is None else f'Some("{signature}")'
    print(f'    ("{name}", {value}),')
print("];")
