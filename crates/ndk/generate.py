"""Generates the EGL and GLES signature tables from the NDK's headers and library stubs.

Each stub lists what a library exports at the NDK's newest API level; each header gives the C
prototype, whose types become the table's closed vocabulary. Run by generate.sh in the dev service.

usage: generate.py <sysroot include dir> <EGL names> <GLESv2 names> <GLESv3 names> <output dir>
"""
import re
import sys

GL_TYPES = {
    "void": "void", "GLenum": "u32", "GLboolean": "u8", "GLbitfield": "u32", "GLbyte": "i8",
    "GLubyte": "u8", "GLshort": "i16", "GLushort": "u16", "GLint": "i32", "GLuint": "u32",
    "GLsizei": "i32", "GLfloat": "f32", "GLclampf": "f32", "GLdouble": "f64", "GLfixed": "i32", "GLclampx": "i32",
    "GLintptr": "i64", "GLsizeiptr": "i64", "GLint64": "i64", "GLuint64": "u64",
    "GLint64EXT": "i64", "GLuint64EXT": "u64", "GLhalf": "u16", "GLsync": "ptr",
    "GLDEBUGPROC": "ptr", "GLDEBUGPROCKHR": "ptr", "GLeglImageOES": "ptr",
    "GLeglClientBufferEXT": "ptr", "GLVULKANPROCNV": "ptr",
}
EGL_TYPES = {
    "void": "void", "EGLBoolean": "u32", "EGLenum": "u32", "EGLint": "i32", "EGLAttrib": "i64",
    "EGLAttribKHR": "i64", "EGLTime": "u64", "EGLTimeKHR": "u64", "EGLuint64KHR": "u64",
    "EGLnsecsANDROID": "i64", "EGLuint64NV": "u64", "EGLsizeiANDROID": "i64",
    "EGLNativeFileDescriptorKHR": "i32",
}
EGL_POINTERS = {
    "EGLDisplay", "EGLConfig", "EGLSurface", "EGLContext", "EGLImage", "EGLImageKHR", "EGLSync",
    "EGLSyncKHR", "EGLClientBuffer", "EGLStreamKHR", "EGLNativeDisplayType", "EGLNativeWindowType",
    "EGLNativePixmapType", "EGLDeviceEXT", "EGLOutputLayerEXT", "EGLOutputPortEXT", "EGLLabelKHR",
    "EGLObjectKHR", "EGLDEBUGPROCKHR", "__eglMustCastToProperFunctionPointerType",
    "EGLSetBlobFuncANDROID", "EGLGetBlobFuncANDROID", "EGLSyncNV",
}
# EGL functions whose Android meaning differs from Mesa's: their bodies are in src/egl.rs.
EGL_TRANSLATED = {
    "eglChooseConfig": "choose_config",
    "eglCreatePlatformWindowSurface": "create_platform_window_surface",
    "eglCreateWindowSurface": "create_window_surface",
    "eglDestroySurface": "destroy_surface",
    "eglGetConfigAttrib": "get_config_attrib",
    "eglGetDisplay": "get_display",
    "eglGetNativeClientBufferANDROID": "get_native_client_buffer",
    "eglGetPlatformDisplay": "get_platform_display",
    "eglGetProcAddress": "get_proc_address",
    "eglPresentationTimeANDROID": "presentation_time",
    "eglSwapBuffers": "swap_buffers",
    "eglSwapBuffersWithDamageKHR": "swap_buffers_with_damage",
}


# Extensions in Khronos's registry that the NDK's gl2ext.h lacks, which drivers still offer and apps
# ask for: (return type, parameters) as a header would spell them.
GL_EXTRA = {
    "glTextureBarrierNV": ("void", "void"),
}


def vocabulary(text, types, pointers):
    text = text.replace("const", " ").strip()
    if "*" in text or "[" in text:
        return "ptr"
    words = text.split()
    candidates = [words[0]] if len(words) == 1 else words[:-1]
    kind = " ".join(candidates)
    if kind in types:
        return types[kind]
    if kind in pointers:
        return "ptr"
    raise SystemExit(f"no vocabulary type for {text!r}")


def prototypes(paths, api, entry, types, pointers):
    found = {}
    pattern = re.compile(api + r"\s+([^;()]*?)\s*" + entry + r"\s+(\w+)\s*\(([^;]*?)\)\s*;", re.S)
    for path in paths:
        for returns, name, parameters in pattern.findall(open(path).read()):
            found[name] = (returns, " ".join(parameters.split()))
    # Only exported names are converted, so extensions the NDK lacks need no vocabulary.
    def signature(name):
        returns, parameters = found[name]
        arguments = [] if parameters in ("", "void") else [
            vocabulary(p, types, pointers) for p in parameters.split(",")
        ]
        return f"{vocabulary(returns + ' x', types, pointers)}({','.join(arguments)})"
    return found, signature


def names(path):
    return sorted({line.split()[-1] for line in open(path) if line.strip()})


def table(name, library, exports, header):
    lines = [header, f"pub static {name}: Table = Table {{", f'    library: "{library}",', "    exports: &["]
    lines += exports
    lines += ["    ],", "};", ""]
    return "\n".join(lines)


def main():
    include, egl_names, gles2_names, gles3_names, out = sys.argv[1:]
    header = "// @generated by crates/ndk/generate.sh from the NDK's headers and stubs. Do not edit.\n"
    gl, gl_signature = prototypes([f"{include}/GLES3/gl32.h", f"{include}/GLES2/gl2ext.h"], "GL_APICALL",
                    "GL_APIENTRY", GL_TYPES, set())
    egl, egl_signature = prototypes([f"{include}/EGL/egl.h", f"{include}/EGL/eglext.h"], "EGLAPI", "EGLAPIENTRY",
                     EGL_TYPES, EGL_POINTERS)

    gles = [header + "\nuse uxdroid_bridge::table::{Export, Table};\n\nuse crate::egl::gles_symbol;\n"]
    for static, library, listing in (("GLESV2", "libGLESv2.so", gles2_names),
                                     ("GLESV3", "libGLESv3.so", gles3_names)):
        exports = []
        for symbol in names(listing):
            if symbol not in gl:
                raise SystemExit(f"{library}: no prototype for {symbol}")
            exports.append(f'        Export::resolved(c"{symbol}", "{gl_signature(symbol)}", gles_symbol),')
        gles.append(table(static, library, exports, ""))
    # Extensions no library exports, signed for eglGetProcAddress from translated code. The name is
    # no file's, so a library never binds to this table through DT_NEEDED. Prototypes whose types
    # the vocabulary lacks are left out, so their lookup stays null.
    gl.update(GL_EXTRA)
    exported = set(names(gles2_names)) | set(names(gles3_names))
    exports = []
    for symbol in sorted(set(gl) - exported):
        try:
            signature = gl_signature(symbol)
        except SystemExit:
            continue
        exports.append(f'        Export::resolved(c"{symbol}", "{signature}", gles_symbol),')
    gles.append(table("GLES_EXTENSIONS", "GLES extensions", exports, ""))
    open(f"{out}/gles_table.rs", "w").write("\n".join(gles))

    exports = []
    for symbol in names(egl_names):
        if symbol not in egl:
            raise SystemExit(f"libEGL.so: no prototype for {symbol}")
        if symbol in EGL_TRANSLATED:
            exports.append(f'        Export::function(c"{symbol}", "{egl_signature(symbol)}", egl::{EGL_TRANSLATED[symbol]} as *const ()),')
        else:
            exports.append(f'        Export::resolved(c"{symbol}", "{egl_signature(symbol)}", egl::egl_symbol),')
    missing = set(EGL_TRANSLATED) - set(names(egl_names))
    if missing:
        raise SystemExit(f"translated functions the NDK does not export: {sorted(missing)}")
    body = header + "\nuse uxdroid_bridge::table::{Export, Table};\n\nuse crate::egl;\n\n"
    open(f"{out}/egl_table.rs", "w").write(body + table("EGL", "libEGL.so", exports, ""))


main()
