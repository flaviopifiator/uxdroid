"""Generates a Context whose every abstract method returns its type's default value.

Usage: default_context.py <javap -p android.content.Context output> <out .java>

Android's Context has more than a hundred abstract methods. An app's context overrides the ones it
needs; the rest answer with zero, false or null instead of being written by hand.
"""

import re
import sys

DEFAULTS = {"boolean": "false", "char": "(char) 0", "byte": "(byte) 0", "short": "(short) 0",
            "int": "0", "long": "0L", "float": "0f", "double": "0d"}
METHOD = re.compile(r"(public|protected) abstract (<.+?> )?(\S+) (\w+)\((.*)\)$")


def java_type(name):
    """javap writes nested classes as Outer$Inner; Java source wants Outer.Inner."""
    return re.sub(r"(\w)\$(\w)", r"\1.\2", name)


def generate(javap_lines):
    out = ["package dev.uxdroid.system;", "",
           "/** Generated by runtime/framework/default_context.py: every abstract Context method returns its type's default. */",
           "public abstract class DefaultContext extends android.content.Context {"]
    seen = set()
    for line in javap_lines:
        line = re.sub(r"\s+throws\s+[^;]+", "", line.strip()).rstrip(";")
        if " abstract " not in line or "(" not in line:
            continue
        match = METHOD.match(line)
        if not match:
            raise ValueError("unparsed Context method: " + line)
        visibility, generic, result, name, params = match.groups()
        types = [java_type(p.strip()) for p in re.split(r",(?![^<]*>)", params) if p.strip()]
        if (name, tuple(types)) in seen:
            continue
        seen.add((name, tuple(types)))
        args = ", ".join("{} a{}".format(t, i) for i, t in enumerate(types))
        body = "" if result == "void" else "return {}; ".format(DEFAULTS.get(result, "null"))
        out.append("    @Override {} {}{} {}({}) {{ {}}}".format(
            visibility, generic or "", java_type(result), name, args, body))
    out.append("}")
    return "\n".join(out) + "\n", len(seen)


if __name__ == "__main__":
    with open(sys.argv[1]) as f:
        source, count = generate(f.read().splitlines())
    with open(sys.argv[2], "w") as f:
        f.write(source)
    print("DefaultContext: {} methods".format(count))
